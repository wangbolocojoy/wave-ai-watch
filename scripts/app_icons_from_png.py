#!/usr/bin/env python3
"""Build LVGL RGB565A8 icon assets from a folder of transparent PNGs.

The PNGs are expected to be square-ish app icons with an alpha channel (for
example the 400x400 files in assets/app-icons). Each one is cropped to its
visible bounds, centred on a square canvas, downscaled to the on-watch size and
written as one C array per icon.

Usage:
    python scripts/app_icons_from_png.py --dir assets/app-icons \
        --out firmware/xiaozhi-esp32/main/boards/<board>/app_icons.c
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

# File prefix -> C symbol suffix, in grid order.
ICON_ORDER = [
    ("01", "assistant"),
    ("02", "music"),
    ("03", "activity"),
    ("04", "alarm"),
    ("05", "timer"),
    ("06", "settings"),
    ("07", "voice_memo"),
    ("08", "photos"),
    ("09", "videos"),
]

ICON_PX = 108

# The app grid page paints this colour behind the icons; baking it into the
# corner pixels lets us drop the 1-byte-per-pixel alpha plane (33% of the flash
# footprint) without any visible difference.
APP_PAGE_RGB = (10, 26, 43)  # 0x0a1a2b


def rounded_alpha(size: int, radius_ratio: float) -> np.ndarray:
    """Analytic rounded-square coverage (0..1), smooth to sub-pixel level."""
    radius = size * radius_ratio
    coords = np.arange(size, dtype=np.float32) + 0.5
    xx, yy = np.meshgrid(coords, coords)
    center = size / 2.0
    half = center - radius
    dx = np.abs(xx - center) - half
    dy = np.abs(yy - center) - half
    outside = np.sqrt(np.maximum(dx, 0.0) ** 2 + np.maximum(dy, 0.0) ** 2)
    inside = np.minimum(np.maximum(dx, dy), 0.0)
    distance = outside + inside - radius
    return np.clip(0.5 - distance, 0.0, 1.0)


def load_icon(path: Path) -> Image.Image:
    image = Image.open(path).convert("RGBA")
    alpha = np.array(image)[:, :, 3]
    rows = np.where((alpha > 8).any(axis=1))[0]
    cols = np.where((alpha > 8).any(axis=0))[0]
    if len(rows) == 0 or len(cols) == 0:
        return image.resize((ICON_PX, ICON_PX), Image.LANCZOS)
    box = (int(cols[0]), int(rows[0]), int(cols[-1]) + 1, int(rows[-1]) + 1)
    cropped = image.crop(box)
    side = max(cropped.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(cropped, ((side - cropped.width) // 2, (side - cropped.height) // 2))

    # The AI-rendered source alpha jumps from 0 to ~250 in a single pixel, which
    # shows up as stair steps at watch size. Intersect it with a smooth rounded
    # square coverage mask, keep the colour data straight (LVGL blends it), and
    # resample the alpha with LANCZOS so the edge gets a proper 1-2 px ramp.
    coverage = rounded_alpha(side, 0.225)
    source = np.array(square).astype(np.float32)
    combined = (source[:, :, 3] / 255.0) * coverage
    rgb_image = Image.fromarray(source[:, :, :3].astype(np.uint8), "RGB").resize(
        (ICON_PX, ICON_PX), Image.LANCZOS)
    alpha_image = Image.fromarray((combined * 255.0).astype(np.uint8), "L").resize(
        (ICON_PX, ICON_PX), Image.LANCZOS)
    # A sub-pixel feather hides the 1 px hard border of the source render.
    alpha_image = alpha_image.filter(ImageFilter.GaussianBlur(0.6))
    result = rgb_image.convert("RGBA")
    result.putalpha(alpha_image)
    return result


def emit(icons: list[tuple[str, Image.Image]], out_path: Path) -> None:
    lines: list[str] = [
        "// Generated by scripts/app_icons_from_png.py - do not edit by hand.\n",
        '#include "app_icons.h"\n\n',
    ]
    for name, icon in icons:
        rgba = np.array(icon).astype(np.uint16)
        r = (rgba[:, :, 0] >> 3) & 0x1F
        g = (rgba[:, :, 1] >> 2) & 0x3F
        b = (rgba[:, :, 2] >> 3) & 0x1F
        rgb565 = ((r << 11) | (g << 5) | b).astype("<u2")
        alpha = rgba[:, :, 3].astype(np.uint8)
        lines.append(f"static const uint8_t app_icon_{name}_map[] = {{\n")
        color_bytes = rgb565.tobytes()
        for offset in range(0, len(color_bytes), 16):
            chunk = color_bytes[offset:offset + 16]
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",\n")
        alpha_bytes = alpha.tobytes()
        for offset in range(0, len(alpha_bytes), 16):
            chunk = alpha_bytes[offset:offset + 16]
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",\n")
        lines.append("};\n\n")
        lines.append(
            f"const lv_image_dsc_t app_icon_{name} = {{\n"
            "    .header = {\n"
            "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            "        .cf = LV_COLOR_FORMAT_RGB565A8,\n"
            "        .flags = 0,\n"
            f"        .w = {ICON_PX},\n"
            f"        .h = {ICON_PX},\n"
            f"        .stride = {ICON_PX * 2},\n"
            "    },\n"
            f"    .data_size = sizeof(app_icon_{name}_map),\n"
            f"    .data = app_icon_{name}_map,\n"
            "};\n\n"
        )
    out_path.write_text("".join(lines), encoding="utf-8")

    header = [
        "#pragma once\n\n",
        "#include <lvgl.h>\n\n",
        f"static constexpr int kAppIconSize = {ICON_PX};\n\n",
        '#ifdef __cplusplus\nextern "C" {\n#endif\n\n',
    ]
    header += [f"LV_IMAGE_DECLARE(app_icon_{name});\n" for _, name in ICON_ORDER]
    header.append('\n#ifdef __cplusplus\n}\n#endif\n')
    out_path.with_suffix(".h").write_text("".join(header), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", type=Path, default=Path("assets/app-icons"))
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    files = {path.name[:2]: path for path in args.dir.glob("*.png")}
    icons: list[tuple[str, Image.Image]] = []
    for prefix, name in ICON_ORDER:
        path = files.get(prefix)
        if path is None:
            raise SystemExit(f"missing icon {prefix}-*.png in {args.dir}")
        icons.append((name, load_icon(path)))
    emit(icons, args.out)
    print(f"wrote {args.out} ({len(icons)} icons, {ICON_PX * ICON_PX * 3 * len(icons) / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
