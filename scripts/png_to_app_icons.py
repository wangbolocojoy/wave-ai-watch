#!/usr/bin/env python3
"""Cut the 3x3 app-icon sheet into LVGL RGB565A8 C arrays.

The sheet is expected to contain nine rounded-square icons in a regular grid
(reading order: assistant, music, activity, alarm, timer, settings, memo,
photos, videos). Every icon gets its own cropped square with a rounded alpha
mask so it can be placed on any background.

Usage:
    python scripts/png_to_app_icons.py sheet.png \
        --out firmware/xiaozhi-esp32/main/boards/<board>/app_icons.c
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

# Reading order of the sheet.
ICON_NAMES = [
    "assistant", "music", "activity",
    "alarm", "timer", "settings",
    "voice_memo", "photos", "videos",
]

ICON_PX = 92
CORNER_RATIO = 0.235
SUPERSAMPLE = 4


def find_icon_bbox(cell: Image.Image) -> tuple[int, int, int, int]:
    """Bounding box of the vividly colored icon inside one grid cell."""
    rgb = np.asarray(cell.convert("RGB")).astype(int)
    # Saturation-ish measure: a white background has R≈G≈B, the icon does not.
    spread = rgb.max(axis=2) - rgb.min(axis=2)
    bright = rgb.mean(axis=2)
    vivid = (spread > 26) & (bright < 250)
    # Ignore a 4 px border that may contain the neighbouring icon's glow.
    vivid[:4, :] = False
    vivid[-4:, :] = False
    vivid[:, :4] = False
    vivid[:, -4:] = False
    rows = np.where(vivid.any(axis=1))[0]
    cols = np.where(vivid.any(axis=0))[0]
    if len(rows) == 0 or len(cols) == 0:
        return 0, 0, cell.width, cell.height
    # Use the flat middle band instead of the extreme corners: neighbouring
    # icons leak a thin glow or shadow into the grid gap, which would otherwise
    # stretch the crop and add colored slivers to the rounded edge.
    y0, y1 = int(rows[0]), int(rows[-1])
    x0, x1 = int(cols[0]), int(cols[-1])
    band_y0 = y0 + (y1 - y0) // 4
    band_y1 = y1 - (y1 - y0) // 4
    band_x0 = x0 + (x1 - x0) // 4
    band_x1 = x1 - (x1 - x0) // 4
    lefts = [np.where(vivid[y])[0][0] for y in range(band_y0, band_y1 + 1) if vivid[y].any()]
    rights = [np.where(vivid[y])[0][-1] for y in range(band_y0, band_y1 + 1) if vivid[y].any()]
    tops = [np.where(vivid[:, x])[0][0] for x in range(band_x0, band_x1 + 1) if vivid[:, x].any()]
    bottoms = [np.where(vivid[:, x])[0][-1] for x in range(band_x0, band_x1 + 1) if vivid[:, x].any()]
    if lefts and rights and tops and bottoms:
        x0, x1 = int(np.median(lefts)), int(np.median(rights))
        y0, y1 = int(np.median(tops)), int(np.median(bottoms))
    # The sheet's rounded squares leave a white margin inside each grid cell;
    # anything vivid within that margin belongs to the neighbouring icon's glow.
    margin = 14
    x0 = max(x0, margin)
    y0 = max(y0, margin)
    x1 = min(x1, cell.width - 1 - margin)
    y1 = min(y1, cell.height - 1 - margin)
    inset = 2
    x0, y0 = x0 + inset, y0 + inset
    x1, y1 = x1 - inset, y1 - inset
    # The rounded square is symmetric; grow the shorter side to a square.
    side = max(x1 - x0, y1 - y0) + 1
    cx = (x0 + x1) // 2
    cy = (y0 + y1) // 2
    half = side // 2
    left = max(0, cx - half)
    top = max(0, cy - half)
    return left, top, min(cell.width, left + side), min(cell.height, top + side)


def rounded_mask(size: int, radius_ratio: float) -> np.ndarray:
    """Anti-aliased rounded-square alpha mask built from a signed distance.

    PIL's rounded_rectangle is not anti-aliased; supersampling it and resizing
    with a sharp kernel rings at the edge (visible stair steps on the watch).
    A distance-based coverage value gives a clean one-pixel ramp instead.
    """
    radius = size * radius_ratio
    coords = np.arange(size, dtype=np.float32) + 0.5
    xx, yy = np.meshgrid(coords, coords)
    center = size / 2.0
    half = center - radius
    dx = np.abs(xx - center) - half
    dy = np.abs(yy - center) - half
    outside = np.sqrt(np.maximum(dx, 0.0) ** 2 + np.maximum(dy, 0.0) ** 2)
    inside = np.minimum(np.maximum(dx, dy), 0.0)
    distance = outside + inside - radius
    coverage = np.clip(0.5 - distance, 0.0, 1.0)
    return np.round(coverage * 255.0).astype(np.uint8)


def rgb565_bytes(icon: Image.Image) -> bytes:
    rgb = np.asarray(icon.convert("RGB")).astype(np.uint16)
    r = (rgb[:, :, 0] >> 3) & 0x1F
    g = (rgb[:, :, 1] >> 2) & 0x3F
    b = (rgb[:, :, 2] >> 3) & 0x1F
    value = (r << 11) | (g << 5) | b
    return value.astype("<u2").tobytes()


def emit_c(icons: list[tuple[str, Image.Image]], out_path: Path) -> None:
    lines: list[str] = []
    lines.append('// Generated by scripts/png_to_app_icons.py - do not edit by hand.\n')
    lines.append('#include "app_icons.h"\n\n')
    for name, icon in icons:
        alpha = rounded_mask(ICON_PX, CORNER_RATIO)
        pixels = rgb565_bytes(icon)
        lines.append(f"static const uint8_t app_icon_{name}_map[] = {{\n")
        for offset in range(0, len(pixels), 16):
            chunk = pixels[offset:offset + 16]
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        for offset in range(0, alpha.size, 16):
            chunk = alpha.reshape(-1)[offset:offset + 16]
            lines.append("    " + ", ".join(f"0x{int(b):02x}" for b in chunk) + ",\n")
        lines.append("};\n\n")
        lines.append(
            f"const lv_image_dsc_t app_icon_{name} = {{\n"
            f"    .header = {{\n"
            f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"        .cf = LV_COLOR_FORMAT_RGB565A8,\n"
            f"        .flags = 0,\n"
            f"        .w = {ICON_PX},\n"
            f"        .h = {ICON_PX},\n"
            f"        .stride = {ICON_PX * 2},\n"
            f"    }},\n"
            f"    .data_size = sizeof(app_icon_{name}_map),\n"
            f"    .data = app_icon_{name}_map,\n"
            f"}};\n\n"
        )
    out_path.write_text("".join(lines), encoding="utf-8")


def emit_h(out_path: Path) -> None:
    lines = [
        "#pragma once\n\n",
        "#include <lvgl.h>\n\n",
        f"static constexpr int kAppIconSize = {ICON_PX};\n\n",
        '#ifdef __cplusplus\nextern "C" {\n#endif\n',
    ]
    for name in ICON_NAMES:
        lines.append(f"LV_IMAGE_DECLARE(app_icon_{name});\n")
    lines.append('#ifdef __cplusplus\n}\n#endif\n')
    out_path.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sheet", type=Path)
    parser.add_argument("--out", type=Path, required=True, help="output .c file")
    args = parser.parse_args()

    sheet = Image.open(args.sheet).convert("RGB")
    cell_w = sheet.width // 3
    cell_h = sheet.height // 3
    icons: list[tuple[str, Image.Image]] = []
    for index, name in enumerate(ICON_NAMES):
        row, col = divmod(index, 3)
        cell = sheet.crop((col * cell_w, row * cell_h, (col + 1) * cell_w, (row + 1) * cell_h))
        # The nine rounded squares are centred in equal grid cells; a fixed
        # centred square keeps the neighbouring icon's glow out of the crop,
        # which bbox detection alone cannot guarantee.
        side = min(cell.width, cell.height) - 36
        left = (cell.width - side) // 2
        top = (cell.height - side) // 2
        icon = cell.crop((left, top, left + side, top + side)).resize((ICON_PX, ICON_PX),
                                                                     Image.LANCZOS)
        # LANCZOS downscaling softens the 3D art; a light unsharp mask keeps the
        # icons crisp at 92 px without bringing the ringing back.
        icon = icon.filter(ImageFilter.UnsharpMask(radius=0.6, percent=55, threshold=2))
        icons.append((name, icon))
    emit_c(icons, args.out)
    emit_h(args.out.with_suffix(".h"))
    total = ICON_PX * ICON_PX * 3 * len(icons)
    print(f"wrote {args.out} ({len(icons)} icons, {total / 1024:.0f} KiB flash)")


if __name__ == "__main__":
    main()
