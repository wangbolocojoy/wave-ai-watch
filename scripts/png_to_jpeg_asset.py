#!/usr/bin/env python3
"""Embed an image as a JPEG byte array so the firmware decodes it at boot.

Flash is the scarce resource in this project (the app partition is 4 MB and the
icons/artwork used to be stored as raw RGB565). A JPEG is 3-8x smaller; the
firmware decodes it into PSRAM once at startup and hands the pixels to LVGL.

Usage:
    python scripts/png_to_jpeg_asset.py assets/whale-girl.png \
        --size 240 240 --bg 0xE8EDFF --name whale_girl_jpeg --out <board dir>
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image


def parse_color(value: str) -> tuple[int, int, int, int]:
    text = value.lower().removeprefix("0x").lstrip("#")
    if len(text) != 6:
        raise SystemExit(f"bad --bg colour: {value}")
    return tuple(int(text[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path)
    parser.add_argument("--size", required=True, nargs=2, type=int, metavar=("W", "H"))
    parser.add_argument("--bg", default="0x000000", help="colour behind transparent pixels")
    parser.add_argument("--quality", type=int, default=90)
    parser.add_argument("--name", required=True, help="C symbol prefix, e.g. whale_girl_jpeg")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    source = Image.open(args.image).convert("RGBA")
    if source.getchannel("A").getextrema()[0] < 255:
        canvas = Image.new("RGBA", source.size, parse_color(args.bg))
        canvas.alpha_composite(source)
        source = canvas
    image = source.convert("RGB")
    # Cover-fit so the artwork keeps its aspect ratio inside the requested box.
    target_w, target_h = args.size
    scale = max(target_w / image.width, target_h / image.height)
    resized = image.resize((max(1, round(image.width * scale)), max(1, round(image.height * scale))),
                           Image.LANCZOS)
    left = (resized.width - target_w) // 2
    top = (resized.height - target_h) // 2
    resized = resized.crop((left, top, left + target_w, top + target_h))

    buffer = Path("/tmp") / f"{args.name}.jpg"
    # TJpgDec (esp_jpeg) mishandles 4:4:4 chroma here (rainbow garbage), so force
    # 4:2:0; at watch sizes the difference is invisible.
    resized.save(buffer, format="JPEG", quality=args.quality, optimize=True,
                 subsampling=2, progressive=False)
    data = buffer.read_bytes()

    header = args.out / f"{args.name}.h"
    source_file = args.out / f"{args.name}.c"
    guard = f"{args.name.upper()}_JPEG_H"
    header.write_text(
        f"#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
        f"#ifdef __cplusplus\nextern \"C\" {{\n#endif\n\n"
        f"extern const uint8_t {args.name}[];\n"
        f"extern const size_t {args.name}_len;\n\n"
        f"#ifdef __cplusplus\n}}\n#endif\n",
        encoding="utf-8",
    )
    lines = [
        f"// Generated by scripts/png_to_jpeg_asset.py from {args.image.name}\n",
        f'#include "{args.name}.h"\n\n',
        f"const uint8_t {args.name}[] = {{\n",
    ]
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    lines.append("};\n")
    lines.append(f"const size_t {args.name}_len = sizeof({args.name});\n")
    source_file.write_text("".join(lines), encoding="utf-8")
    print(f"{args.name}: {target_w}x{target_h} q{args.quality} -> {len(data) / 1024:.0f} KiB flash "
          f"(was {target_w * target_h * 2 / 1024:.0f} KiB as RGB565)")


if __name__ == "__main__":
    main()
