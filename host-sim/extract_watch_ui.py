#!/usr/bin/env python3
"""Extract the firmware CustomLcdDisplay class into a host-compilable header.

The host build deliberately uses the exact class text from the board source. This keeps
the firmware UI as the single source of truth without duplicating the 1000+ line view
layer in the host project.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
BOARD = ROOT.parent / "firmware/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.06/esp32-s3-touch-amoled-2.06.cc"
OUT = ROOT / "generated/watch_display_ui.h"

if len(sys.argv) >= 2:
    BOARD = Path(sys.argv[1])
if len(sys.argv) >= 3:
    OUT = Path(sys.argv[2])

source = BOARD.read_text(encoding="utf-8")
start_marker = "class CustomLcdDisplay : public SpiLcdDisplay {"
end_marker = "class CustomBacklight"
start = source.find(start_marker)
if start < 0:
    raise SystemExit(f"CustomLcdDisplay not found in {BOARD}")
end = source.find(end_marker, start)
if end < 0:
    raise SystemExit("CustomBacklight not found after CustomLcdDisplay")
class_text = source[start:end].rstrip()
if not class_text.endswith("};"):
    raise SystemExit("extracted class does not end with };")

header = '''// Generated by host-sim/extract_watch_ui.py. Do not edit.
// Source: firmware/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.06/esp32-s3-touch-amoled-2.06.cc
#pragma once

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <ctime>
#include <functional>
#include <string>
#include <vector>

#include <lvgl.h>

#include "display/lcd_display.h"
#include "application.h"
#include "assets/lang_config.h"
#include "board.h"
#include "settings.h"
#include "watch_activity_service.h"
#include "watch_alarm_service.h"
#include "watch_music_player.h"
#include "watch_timer_service.h"
#include "material_symbols.h"
#include "watch_fonts.h"
#include "whale_girl_image.h"

LV_FONT_DECLARE(font_material_symbols_30_4);

''' + class_text + "\n"

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(header, encoding="utf-8")
print(f"generated {OUT} ({len(class_text.splitlines())} class lines)")
